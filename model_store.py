"""Fixed infrastructure: where trained models live, how they are validated, cached and replaced.

Students do not edit this file. `regression.py` only needs:
    model_store.model_paths(model_dir)   -> where to save the three models
    model_store.load_models(model_dir)   -> (pitch_model, yaw_model, roll_model) or None
"""
from __future__ import annotations

import json
import os
import shutil
import tempfile
import threading
from datetime import datetime, timezone
from pathlib import Path

import joblib

import config


class ModelStoreError(Exception):
    pass


# ---------------------------------------------------------------------------
# Paths and metadata
# ---------------------------------------------------------------------------
def model_paths(model_dir):
    """{'pitch': Path, 'yaw': Path, 'roll': Path} inside model_dir."""
    folder = Path(model_dir)
    return {name: folder / filename for name, filename in config.MODEL_FILENAMES.items()}


def read_metadata(model_dir):
    try:
        with (Path(model_dir) / config.METADATA_FILENAME).open("r", encoding="utf-8") as file:
            data = json.load(file)
    except (OSError, ValueError):
        return None
    return data if isinstance(data, dict) else None


def write_metadata(model_dir, model_type, alpha, n_samples=0, dataset_path="", extra=None):
    data = {
        "format_version": config.MODEL_FORMAT_VERSION,
        "feature_version": config.FEATURE_VERSION,
        "num_landmarks": config.NUM_LANDMARKS,
        "angle_unit": config.MODEL_ANGLE_UNIT,
        "model_type": str(model_type),
        "alpha": float(alpha),
        "n_samples": int(n_samples),
        "dataset_path": str(dataset_path),
        "trained_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    if extra:
        data["extra"] = extra
    target = Path(model_dir) / config.METADATA_FILENAME
    temporary = target.with_suffix(".tmp")
    with temporary.open("w", encoding="utf-8") as file:
        json.dump(data, file, indent=2)
    os.replace(temporary, target)       # metadata is written last: it marks a complete set
    return data


def check_models(model_dir):
    """Return (status, message, metadata); status is 'ok', 'missing' or 'incompatible'."""
    paths = model_paths(model_dir)
    metadata = read_metadata(model_dir)
    if metadata is None:
        if any(path.exists() for path in paths.values()):
            return "incompatible", "Model files exist but metadata.json is missing or unreadable.", None
        return "missing", "No trained models found.", None

    expected = {
        "format_version": config.MODEL_FORMAT_VERSION,
        "feature_version": config.FEATURE_VERSION,
        "num_landmarks": config.NUM_LANDMARKS,
        "angle_unit": config.MODEL_ANGLE_UNIT,
    }
    for key, value in expected.items():
        if metadata.get(key) != value:
            return "incompatible", f"Saved models use {key}={metadata.get(key)!r}, expected {value!r}.", metadata
    absent = [path.name for path in paths.values() if not path.is_file()]
    if absent:
        return "incompatible", f"Missing model file(s): {', '.join(absent)}.", metadata
    return "ok", "Trained models are ready.", metadata


# ---------------------------------------------------------------------------
# Cached loading (used by predict_angles on every frame)
# ---------------------------------------------------------------------------
_lock = threading.Lock()
_cache = {"key": None, "models": None, "failed_key": None}


def clear_cache():
    with _lock:
        _cache.update(key=None, models=None, failed_key=None)


def load_models(model_dir):
    """Return (pitch_model, yaw_model, roll_model), or None if no valid compatible set exists.

    Models are read from disk only when metadata.json changes, so calling this for every video
    frame costs one os.stat(). The returned tuple is never modified, so a worker thread always
    sees a consistent set even while a new set is being installed.
    """
    metadata_path = Path(model_dir) / config.METADATA_FILENAME
    try:
        stat = os.stat(metadata_path)
        key = (str(model_dir), stat.st_mtime_ns, stat.st_size)
    except OSError:
        with _lock:   # during the brief swap in install_staging keep using the last good set
            if _cache["models"] is not None and _cache["key"] and _cache["key"][0] == str(model_dir):
                return _cache["models"]
        return None

    with _lock:
        if _cache["key"] == key:
            return _cache["models"]
        if _cache["failed_key"] == key:
            return None
        status, _, _ = check_models(model_dir)
        models = None
        if status == "ok":
            try:
                loaded = tuple(joblib.load(model_paths(model_dir)[name]) for name in config.ANGLE_NAMES)
                if all(hasattr(model, "predict") for model in loaded):
                    models = loaded
            except Exception:
                models = None
        if models is None:
            _cache["failed_key"] = key
            return None
        _cache.update(key=key, models=models, failed_key=None)
        return models


# ---------------------------------------------------------------------------
# Safe install / delete
# ---------------------------------------------------------------------------
def _assert_safe_model_dir(model_dir):
    folder = Path(model_dir).resolve()
    if folder == config.MODELS_DIR.resolve() or (folder / "face_landmarker.task").exists():
        raise ModelStoreError(f"Refusing to modify {folder}: it contains the MediaPipe task file.")
    return folder


def install_staging(staging_dir, target_dir):
    """Replace target_dir by staging_dir; the old set is restored if anything fails."""
    target = _assert_safe_model_dir(target_dir)
    target.parent.mkdir(parents=True, exist_ok=True)
    backup = target.with_name(target.name + ".old")
    had_old = target.exists()
    if had_old:
        if backup.exists():
            shutil.rmtree(backup, ignore_errors=True)
        os.replace(target, backup)
    try:
        os.replace(staging_dir, target)
    except Exception:
        if had_old:
            os.replace(backup, target)
        raise
    if had_old:
        shutil.rmtree(backup, ignore_errors=True)
    clear_cache()


def delete_trained_models(model_dir=None):
    """Delete ONLY the three model files and metadata.json. Returns the removed file names."""
    folder = _assert_safe_model_dir(model_dir or config.TRAINED_MODELS_DIR)
    removed = []
    for filename in (*config.MODEL_FILENAMES.values(), config.METADATA_FILENAME):
        path = folder / filename
        if path.is_file():
            path.unlink()
            removed.append(filename)
    try:
        folder.rmdir()                 # only succeeds if the folder is now empty
    except OSError:
        pass
    clear_cache()
    return removed


def train_and_install(train_fn, dataset_path, model_type, alpha, target_dir=None):
    """Run the student's train_fn into a staging folder; install it only if everything is valid.

    A failed or interrupted training therefore never touches the previously valid models.
    """
    target = Path(target_dir or config.TRAINED_MODELS_DIR)
    target.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=".staging_", dir=target.parent))
    try:
        result = train_fn(str(dataset_path), model_type, str(staging), alpha)
        if not isinstance(result, dict):
            return {"success": False, "message": "train_models() must return a dict with 'success' and 'message'."}
        if not result.get("success"):
            result.setdefault("message", "Training failed.")
            return result

        for name, path in model_paths(staging).items():
            if not path.is_file():
                return {"success": False, "message": f"train_models() reported success but {path.name} was not saved."}
            model = joblib.load(path)
            if not hasattr(model, "predict"):
                return {"success": False, "message": f"{path.name} is not a fitted scikit-learn model."}
            n_in = getattr(model, "n_features_in_", config.NUM_FEATURES)
            if n_in != config.NUM_FEATURES:
                return {"success": False, "message": f"{path.name} expects {n_in} features, but the feature vector has {config.NUM_FEATURES}."}

        write_metadata(staging, model_type, alpha, result.get("n_samples", 0), Path(dataset_path).resolve(),
                       extra={k: v for k, v in result.items() if k in ("val_mae_deg", "n_skipped")} or None)
        install_staging(staging, target)
        result = dict(result)
        result["model_dir"] = str(target)
        return result
    finally:
        shutil.rmtree(staging, ignore_errors=True)


# ---------------------------------------------------------------------------
# Dataset header check (cheap; the real validation happens in train_models)
# ---------------------------------------------------------------------------
def inspect_dataset(path):
    """Return (ok, message). Reads only the header and counts rows."""
    import csv
    path = Path(path)
    if not path.is_file():
        return False, f"File not found: {path}"
    if path.suffix.lower() != ".csv":
        return False, f"Unsupported file type '{path.suffix}'. Please select a .csv dataset file."
    try:
        with path.open("r", encoding="utf-8-sig", newline="") as file:
            header = next(csv.reader(file), None)
            rows = sum(1 for _ in file)
    except (OSError, UnicodeDecodeError) as exc:
        return False, f"Could not read the file: {exc}"
    if not header:
        return False, "The file is empty."
    expected = ["pitch", "yaw", "roll"]
    for index in range(config.NUM_LANDMARKS):
        expected += [f"x_{index}", f"y_{index}"]
    missing = [column for column in expected if column not in set(header)]
    if missing:
        return False, f"Missing {len(missing)} required column(s), e.g. {', '.join(missing[:4])}."
    return True, f"Dataset OK: {rows} rows, {config.NUM_LANDMARKS} landmarks."
