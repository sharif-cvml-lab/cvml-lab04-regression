"""Fixed infrastructure: MediaPipe landmark extraction + the shared feature preprocessing.

Students do not edit this file. `landmarks_to_feature_vector` is the ONE place that defines
how landmarks become model inputs; training, inference, the GUI and the examples all use it.
"""
from __future__ import annotations

import cv2
import numpy as np

import mediapipe as mp
from mediapipe.tasks.python import vision
from mediapipe.tasks.python.core.base_options import BaseOptions
from mediapipe.tasks.python.vision.face_landmarker import FaceLandmarker, FaceLandmarkerOptions

from config import (
    CENTER_LANDMARK_IDX,
    MIN_SCALE_DISTANCE,
    NUM_LANDMARKS,
    SCALE_LANDMARK_A,
    SCALE_LANDMARK_B,
)


class FaceLandmarkExtractor:
    """Wraps MediaPipe Face Landmarker. Create ONCE and reuse; not thread-safe."""

    def __init__(self, model_asset_path):
        options = FaceLandmarkerOptions(
            base_options=BaseOptions(model_asset_path=str(model_asset_path)),
            running_mode=vision.RunningMode.IMAGE,
            num_faces=1,
        )
        self.detector = FaceLandmarker.create_from_options(options)

    def extract_landmarks(self, image):
        """Return a (478, 2) float32 array of (x, y) PIXEL coordinates, or None.

        image: BGR uint8 image from OpenCV. None means: no face / unusable result.
        Row i holds landmark i, so the order matches the CSV columns x_i, y_i.
        """
        if image is None or image.ndim != 3 or image.shape[2] != 3 or image.dtype != np.uint8:
            return None

        rgb = np.ascontiguousarray(cv2.cvtColor(image, cv2.COLOR_BGR2RGB))
        result = self.detector.detect(mp.Image(image_format=mp.ImageFormat.SRGB, data=rgb))
        if not result.face_landmarks:
            return None

        height, width = image.shape[:2]
        face = result.face_landmarks[0]
        points = np.array([[lm.x * width, lm.y * height] for lm in face], dtype=np.float32)
        if points.shape != (NUM_LANDMARKS, 2) or not np.isfinite(points).all():
            return None
        return points

    def close(self):
        try:
            self.detector.close()
        except Exception:
            pass


def landmarks_to_feature_vector(points):
    """Convert (478, 2) pixel landmarks to a translation- and scale-normalized feature vector.

    1. Translation: subtract landmark 99, so the face position in the image does not matter.
    2. Scale: divide by the distance between landmarks 10 and 171, so face size does not matter.
    3. Layout: [x_0 .. x_477, y_0 .. y_477]  ->  shape (956,)

    Returns None for anything unusable (wrong shape, NaN/inf, degenerate reference distance).
    """
    try:
        points = np.asarray(points, dtype=np.float64)
    except (TypeError, ValueError):
        return None
    if points.shape != (NUM_LANDMARKS, 2) or not np.isfinite(points).all():
        return None

    centered = points - points[CENTER_LANDMARK_IDX]
    scale = np.linalg.norm(points[SCALE_LANDMARK_A] - points[SCALE_LANDMARK_B])
    if not np.isfinite(scale) or scale < MIN_SCALE_DISTANCE:
        return None

    normalized = centered / scale
    return np.hstack([normalized[:, 0], normalized[:, 1]])


def annotate_face_landmarks(image, points, color=(0, 255, 0), radius=1, draw_index=False):
    """Return a copy of `image` with landmark dots (and optionally their indices) drawn."""
    annotated = image.copy()
    for index, (x, y) in enumerate(points):
        center = (int(round(x)), int(round(y)))
        cv2.circle(annotated, center, radius, color, -1, cv2.LINE_AA if radius > 1 else cv2.LINE_8)
        if draw_index:
            cv2.putText(annotated, str(index), (center[0] + 2, center[1] - 2),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.3, (0, 0, 255), 1, cv2.LINE_AA)
    return annotated
